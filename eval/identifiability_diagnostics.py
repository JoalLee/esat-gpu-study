"""Diagnostics for whether distributional source-profile variability is separable.

These diagnostics translate the synthetic identifiability findings into
quantities that can be evaluated on a fitted receptor model. They do *not*
prove identifiability from a single real-data solution; they expose geometric
warning signs that were shown to degrade recovery in controlled simulations.

Two distinct failure modes are measured:

1. global source-type overlap: the archetypal profiles are themselves nearly
   collinear, so W is difficult to separate even before profile variability is
   introduced;
2. W/F confounding: learned profile-family directions lie inside the tangent
   span generated by redistributing W among static archetypes.

For normalized archetypes F_bar, define the static tangent span

    S = span{F_bar[2] - F_bar[1], ..., F_bar[K] - F_bar[1]}.

For an active profile-family direction l, the squared overlap

    a = || P_S l ||^2 / ||l||^2

is one when the direction is fully reproducible by the static factor mixture
and zero when it is orthogonal to that mixture geometry.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass

import numpy as np
import pandas as pd


_EPS = 1e-12


def normalize_profiles(archetypes: np.ndarray) -> np.ndarray:
    profiles = np.asarray(archetypes, dtype=np.float64)
    if profiles.ndim != 2:
        raise ValueError("archetypes must be a K x J matrix")
    if profiles.shape[0] < 1 or profiles.shape[1] < 2:
        raise ValueError("archetypes must contain at least one factor and two features")
    if not np.isfinite(profiles).all() or np.any(profiles < 0.0):
        raise ValueError("archetypes must be finite and non-negative")
    row_sum = profiles.sum(axis=1, keepdims=True)
    if np.any(row_sum <= _EPS):
        raise ValueError("every archetype must have positive total mass")
    return profiles / row_sum


def orthonormal_row_basis(matrix: np.ndarray, tol: float = 1e-10) -> np.ndarray:
    matrix = np.asarray(matrix, dtype=np.float64)
    if matrix.ndim != 2:
        raise ValueError("matrix must be 2-D")
    if matrix.shape[0] == 0 or not np.any(np.abs(matrix) > tol):
        return np.zeros((0, matrix.shape[1]), dtype=np.float64)
    _, singular_values, vt = np.linalg.svd(matrix, full_matrices=False)
    if singular_values.size == 0:
        return np.zeros((0, matrix.shape[1]), dtype=np.float64)
    threshold = max(tol, tol * float(singular_values[0]))
    rank = int(np.sum(singular_values > threshold))
    return vt[:rank]


def static_factor_span(archetypes: np.ndarray) -> np.ndarray:
    """Orthonormal basis of the normalized static factor-difference span."""
    profiles = normalize_profiles(archetypes)
    if profiles.shape[0] <= 1:
        return np.zeros((0, profiles.shape[1]), dtype=np.float64)
    return orthonormal_row_basis(profiles[1:] - profiles[0])


def pairwise_cosine_matrix(archetypes: np.ndarray) -> np.ndarray:
    profiles = normalize_profiles(archetypes)
    norms = np.maximum(np.linalg.norm(profiles, axis=1), _EPS)
    cosine = (profiles @ profiles.T) / (norms[:, None] * norms[None, :])
    return np.clip(cosine, -1.0, 1.0)


def archetype_separation_summary(archetypes: np.ndarray) -> dict[str, float]:
    profiles = normalize_profiles(archetypes)
    cosine = pairwise_cosine_matrix(profiles)
    if profiles.shape[0] <= 1:
        mean_cos = 1.0
        max_cos = 1.0
        min_cos = 1.0
    else:
        upper = cosine[np.triu_indices(profiles.shape[0], k=1)]
        mean_cos = float(np.mean(upper))
        max_cos = float(np.max(upper))
        min_cos = float(np.min(upper))

    differences = profiles[1:] - profiles[0] if profiles.shape[0] > 1 else np.zeros((0, profiles.shape[1]))
    singular_values = np.linalg.svd(differences, compute_uv=False) if differences.shape[0] else np.array([], dtype=float)
    if singular_values.size:
        nonzero = singular_values[singular_values > max(1e-12, 1e-10 * singular_values[0])]
    else:
        nonzero = np.array([], dtype=float)

    if nonzero.size >= 2:
        condition_number = float(nonzero[0] / nonzero[-1])
        minimum_relative_singular_value = float(nonzero[-1] / nonzero[0])
    elif nonzero.size == 1:
        condition_number = 1.0
        minimum_relative_singular_value = 1.0
    else:
        condition_number = float("inf")
        minimum_relative_singular_value = 0.0

    return {
        "pairwise_cosine_mean": mean_cos,
        "pairwise_cosine_max": max_cos,
        "pairwise_cosine_min": min_cos,
        "difference_span_rank": int(nonzero.size),
        "difference_condition_number": condition_number,
        "difference_min_relative_singular_value": minimum_relative_singular_value,
    }


def direction_span_alignment(direction: np.ndarray, span_basis: np.ndarray) -> float:
    direction = np.asarray(direction, dtype=np.float64)
    if direction.ndim != 1:
        raise ValueError("direction must be a vector")
    norm = float(np.linalg.norm(direction))
    if norm <= _EPS:
        return float("nan")
    basis = np.asarray(span_basis, dtype=np.float64)
    if basis.ndim != 2 or basis.shape[1] != direction.size:
        raise ValueError("span_basis must be R x J with same feature dimension")
    if basis.shape[0] == 0:
        return 0.0
    unit = direction / norm
    projection = basis.T @ (basis @ unit)
    return float(np.clip(np.dot(projection, projection), 0.0, 1.0))


def factor_family_alignments(
    archetypes: np.ndarray,
    loadings: np.ndarray,
    effective_rank: np.ndarray | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """Return direction-level and factor-level W/F span alignments.

    Returns
    -------
    direction_alignment
        K x R matrix. Inactive directions are NaN.
    factor_alignment
        K-vector equal to the mean active direction overlap per factor. Static
        factors with no active directions are NaN rather than zero because
        there is no learned variability direction to diagnose.
    """
    profiles = normalize_profiles(archetypes)
    loadings = np.asarray(loadings, dtype=np.float64)
    if loadings.ndim != 3:
        raise ValueError("loadings must be K x R x J")
    if loadings.shape[0] != profiles.shape[0] or loadings.shape[2] != profiles.shape[1]:
        raise ValueError("loadings must match archetype factor/feature dimensions")

    if effective_rank is None:
        active_rank = np.full(loadings.shape[0], loadings.shape[1], dtype=int)
    else:
        active_rank = np.asarray(effective_rank, dtype=int)
        if active_rank.shape != (loadings.shape[0],):
            raise ValueError("effective_rank must have one value per factor")
        active_rank = np.clip(active_rank, 0, loadings.shape[1])

    span = static_factor_span(profiles)
    direction_alignment = np.full(loadings.shape[:2], np.nan, dtype=np.float64)
    factor_alignment = np.full(loadings.shape[0], np.nan, dtype=np.float64)

    for k in range(loadings.shape[0]):
        values: list[float] = []
        for r in range(int(active_rank[k])):
            value = direction_span_alignment(loadings[k, r], span)
            direction_alignment[k, r] = value
            if np.isfinite(value):
                values.append(value)
        if values:
            factor_alignment[k] = float(np.mean(values))

    return direction_alignment, factor_alignment


def _risk_label(
    span_alignment: float,
    max_pairwise_cosine: float,
    *,
    alignment_warning: float,
    alignment_high: float,
    cosine_warning: float,
    cosine_high: float,
) -> str:
    """Provisional geometric warning label, not a calibrated probability."""
    high_alignment = np.isfinite(span_alignment) and span_alignment >= alignment_high
    warn_alignment = np.isfinite(span_alignment) and span_alignment >= alignment_warning
    high_cosine = max_pairwise_cosine >= cosine_high
    warn_cosine = max_pairwise_cosine >= cosine_warning
    if high_alignment or high_cosine:
        return "high_geometric_confounding"
    if warn_alignment or warn_cosine:
        return "moderate_geometric_confounding"
    if np.isnan(span_alignment):
        return "static_or_no_active_family"
    return "lower_geometric_confounding"


@dataclass(frozen=True)
class IdentifiabilityDiagnostics:
    global_summary: dict[str, float]
    direction_alignment: np.ndarray
    factor_alignment: np.ndarray
    factor_table: pd.DataFrame

    def to_dict(self) -> dict:
        return {
            "global_summary": dict(self.global_summary),
            "direction_alignment": self.direction_alignment.tolist(),
            "factor_alignment": self.factor_alignment.tolist(),
            "factor_table": self.factor_table.to_dict(orient="records"),
        }


def diagnose_distributional_solution(
    archetypes: np.ndarray,
    loadings: np.ndarray,
    effective_rank: np.ndarray | None = None,
    profile_rms_variability: np.ndarray | None = None,
    latent_tau: np.ndarray | None = None,
    *,
    alignment_warning: float = 0.50,
    alignment_high: float = 0.75,
    cosine_warning: float = 0.90,
    cosine_high: float = 0.97,
) -> IdentifiabilityDiagnostics:
    """Diagnose fitted low-rank source-type geometry.

    Threshold labels are intentionally described as *provisional*. They are
    operational flags derived from the current pilot phase diagrams, not
    calibrated error probabilities or statistical significance cutoffs.
    Continuous metrics should be reported alongside every label.
    """
    profiles = normalize_profiles(archetypes)
    direction_alignment, factor_alignment = factor_family_alignments(
        profiles,
        loadings,
        effective_rank=effective_rank,
    )
    global_summary = archetype_separation_summary(profiles)

    k = profiles.shape[0]
    if effective_rank is None:
        ranks = np.full(k, loadings.shape[1], dtype=int)
    else:
        ranks = np.asarray(effective_rank, dtype=int)
    if profile_rms_variability is None:
        variability = np.full(k, np.nan)
    else:
        variability = np.asarray(profile_rms_variability, dtype=np.float64)
        if variability.shape != (k,):
            raise ValueError("profile_rms_variability must have one value per factor")
    if latent_tau is None:
        tau = np.full(k, np.nan)
    else:
        tau = np.asarray(latent_tau, dtype=np.float64)
        if tau.shape != (k,):
            raise ValueError("latent_tau must have one value per factor")

    cosine = pairwise_cosine_matrix(profiles)
    rows: list[dict] = []
    for factor in range(k):
        other = np.delete(cosine[factor], factor)
        max_other = float(np.max(other)) if other.size else 1.0
        rows.append(
            {
                "factor": factor,
                "effective_rank": int(ranks[factor]),
                "profile_rms_variability": float(variability[factor]),
                "latent_tau": float(tau[factor]),
                "span_alignment": float(factor_alignment[factor]),
                "unique_direction_fraction": (
                    float(1.0 - factor_alignment[factor])
                    if np.isfinite(factor_alignment[factor])
                    else float("nan")
                ),
                "max_cosine_to_other_archetype": max_other,
                "diagnostic_label": _risk_label(
                    float(factor_alignment[factor]),
                    max_other,
                    alignment_warning=alignment_warning,
                    alignment_high=alignment_high,
                    cosine_warning=cosine_warning,
                    cosine_high=cosine_high,
                ),
            }
        )

    return IdentifiabilityDiagnostics(
        global_summary=global_summary,
        direction_alignment=direction_alignment,
        factor_alignment=factor_alignment,
        factor_table=pd.DataFrame(rows),
    )


def diagnose_lowrank_model(model) -> IdentifiabilityDiagnostics:
    """Convenience wrapper for a fitted ``LowRankDistributionalSA`` instance."""
    required = (
        "H_bar",
        "loadings",
        "effective_rank",
        "profile_rms_variability",
        "latent_tau",
    )
    missing = [name for name in required if getattr(model, name, None) is None]
    if missing:
        raise RuntimeError(f"model is not fitted or missing diagnostics fields: {missing}")
    return diagnose_distributional_solution(
        archetypes=model.H_bar,
        loadings=model.loadings,
        effective_rank=model.effective_rank,
        profile_rms_variability=model.profile_rms_variability,
        latent_tau=model.latent_tau,
    )
